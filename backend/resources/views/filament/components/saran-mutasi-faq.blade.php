<div class="prose prose-sm dark:prose-invert">
    <p>
        <strong>Saran Mutasi Stok AI (Inter-Branch Rebalancing)</strong> membantu manajemen dan kepala cabang mengoptimalkan perputaran barang antar toko fisik tanpa harus mengeluarkan modal baru untuk membeli ke supplier.
    </p>

    <h4 class="font-bold text-gray-800 dark:text-gray-200 mt-3 mb-1">🔍 Cara Membaca Rekomendasi:</h4>
    <ul class="list-disc pl-5 space-y-1">
        <li>
            <strong>Cabang Tujuan (Membutuhkan)</strong>: Cabang di mana barang ini sangat laris terjual, namun stoknya sudah habis (0) atau kritis (cukup untuk &le; 7 hari).
        </li>
        <li>
            <strong>Cabang Pengirim (Surplus/Donor)</strong>: Cabang lain yang memiliki stok berlebih, namun perputaran penjualannya sangat lambat (slow moving) atau bahkan macet (dead stock).
        </li>
        <li>
            <strong>Analisa DOH (Days of Hand)</strong>: Menunjukkan perbandingan usia stok. Contoh: <em>"Pengirim: 300 Hari (Macet) ➔ Tujuan: 1 Hari (Kritis)"</em>.
        </li>
        <li>
            <strong>Qty Disarankan & Sisa Aman Cabang Pengirim</strong>: Sistem secara ketat menghitung cadangan minimal (30 hari penjualan) di cabang pengirim, sehingga cabang pengirim <strong>tidak akan tekor</strong> pasca-transfer.
        </li>
    </ul>

    <h4 class="font-bold text-gray-800 dark:text-gray-200 mt-4 mb-1">🚚 Pengiriman Fleksibel (On-Demand):</h4>
    <p>
        Sistem ini <strong>tidak mengunci kuota minimal kendaraan</strong>. Kapan pun ada mobil operasional yang berkeliling:
    </p>
    <ul class="list-disc pl-5 space-y-1">
        <li>Anda dapat mencentang 1 atau beberapa barang yang siap dimuat, lalu klik <strong>"Kirim Barang Terpilih"</strong>.</li>
        <li>Satu dokumen Surat Jalan Transfer otomatis terbit, nota siap dicetak, dan langsung dapat dititipkan ke pengemudi.</li>
    </ul>

    <div class="mt-4 p-3 bg-purple-50 dark:bg-purple-950/40 rounded-lg text-sm border-l-4 border-purple-500 text-purple-900 dark:text-purple-200">
        <strong>💡 Manfaat Finansial:</strong> Setiap mutasi yang berhasil menghemat arus kas perusahaan (*cash flow*) karena menyelamatkan modal mati menjadi omset nyata tanpa perlu membuat utang/PO baru ke supplier!
